    fun t(key: String, defaultVal: String = key): String {
        val lang = _currentLang.value
        return translations[lang]?.get(key) ?: translations["en"]?.get(key) ?: defaultVal
    }

    /** Translated text with the "{n}" placeholder replaced (e.g. "Connected to {n}"). */
    fun tn(key: String, defaultVal: String, n: Any): String =
        t(key, defaultVal).replace("{n}", n.toString())

    /**
     * Country name in the selected language.
     * 1) hand-written name from the dictionary, 2) the phone's own localized region name
     * (covers every country, same idea as Intl.DisplayNames on Windows), 3) the server's name.
     */
    fun getCountryName(countryCode: String, defaultName: String): String {
        val code = countryCode.uppercase()
        val lang = _currentLang.value
        translations[lang]?.get("country_$code")?.let { return it }
        if (code.length == 2) {
            val localized = java.util.Locale("", code).getDisplayCountry(java.util.Locale(lang))
            if (localized.isNotBlank() && !localized.equals(code, ignoreCase = true)) return localized
        }
        return translations["en"]?.get("country_$code") ?: defaultName
    }

    /** Debug helper: keys that exist in English but are missing in another language (should be empty). */
    fun missingKeys(): Map<String, List<String>> {
        val en = translations["en"].orEmpty().keys
        return translations.filterKeys { it != "en" }
            .mapValues { (_, map) -> en.filter { it !in map.keys } }
            .filterValues { it.isNotEmpty() }
    }
